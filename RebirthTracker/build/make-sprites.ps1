# make-sprites.ps1 - build the deduplicated droid sprite library.
#
# 360 cells collapse to one tile per droid+rarity. Source cell is chosen preferring an
# occurrence with no SELL banner (cleaner corner art); the badge corners are painted out
# regardless so a single tile is valid wherever that droid+rarity appears.
#
# Output: sprites.js  ->  window.SPRITES = { "NAME|RARITY": "data:image/jpeg;base64,..." }

. "$PSScriptRoot\ImgLib.ps1"
. "$PSScriptRoot\grid.ps1"

# sprite region inside a cell: skip the frame, and skip the bottom band that holds the
# poster's own rarity/name text (the app draws its own labels).
$PAD_L = 13; $PAD_T = 13; $SPR_W = 212; $SPR_H = 162
$OUT_W = 212; $OUT_H = 162
$MASK_TRI = 112      # SELL banner: right-triangle legs, in source px. Only applied when the
                     # chosen source cell actually carries a banner - on those cells the art
                     # under the corner is already hidden, so nothing is lost.
$MASK_TR_W = 58      # max-quality icon box, in source px
$MASK_TR_H = 46
$MASK_BL_W = 34      # droid-class chip, bottom-left, in source px
$MASK_BL_H = 30
$QUALITY = 80

# --- pick the best source cell for each droid+rarity ----------------------------------
$best = @{}    # key -> @{ cycle; level; slot; rank }
$rank = @{ "-" = 0; "R" = 1; "Y" = 2 }

foreach ($c in 1..4) {
    $data = Get-Content (Join-Path $PSScriptRoot "cycle$c.json") -Raw | ConvertFrom-Json
    for ($i = 0; $i -lt 30; $i++) {
        for ($s = 0; $s -lt 3; $s++) {
            $d = $data.levels[$i][$s]
            $key = "$($d.n)|$($d.r)"
            $rk = $rank[$d.b]
            if (-not $best.ContainsKey($key) -or $rk -lt $best[$key].rank) {
                $best[$key] = @{ cycle = $c; level = $i + 1; slot = $s; rank = $rk }
            }
        }
    }
}

Write-Output "unique droid+rarity tiles: $($best.Count)"

# --- cut the tiles, grouped by source poster so each JPEG is opened once ---------------
$sprites = @{}
foreach ($c in 1..4) {
    $keys = @($best.Keys | Where-Object { $best[$_].cycle -eq $c })
    if ($keys.Count -eq 0) { continue }
    $src = Join-Path $PSScriptRoot "..\..\Cycle $c.jpg"
    $img = New-Object ImgLib.Img ((Resolve-Path $src).Path)
    foreach ($k in $keys) {
        $b = $best[$k]
        $r = Get-CellRect -Level $b.level -Slot $b.slot
        $tri = if ($b.rank -eq 0) { 0 } else { $MASK_TRI }   # rank 0 == no banner on the source
        $bytes = $img.SpriteJpeg(($r.X + $PAD_L), ($r.Y + $PAD_T), $SPR_W, $SPR_H,
                                 $OUT_W, $OUT_H, $tri, $MASK_TR_W, $MASK_TR_H,
                                 $MASK_BL_W, $MASK_BL_H, $QUALITY)
        $sprites[$k] = [Convert]::ToBase64String($bytes)
    }
    $img.Dispose()
    Write-Output "cycle ${c}: cut $($keys.Count) tiles"
}

# --- emit sprites.js -------------------------------------------------------------------
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by build/make-sprites.ps1 - droid art cut from the Cycle 1-4 posters.")
[void]$sb.AppendLine("// Key is NAME|RARITY. Corner badges are painted out; the app draws its own.")
[void]$sb.AppendLine("window.SPRITES = {")
foreach ($k in ($sprites.Keys | Sort-Object)) {
    [void]$sb.AppendLine("`"$k`":`"data:image/jpeg;base64,$($sprites[$k])`",")
}
[void]$sb.AppendLine("};")

$outPath = Join-Path $PSScriptRoot "sprites.js"
[System.IO.File]::WriteAllText($outPath, $sb.ToString())
$kb = [math]::Round((Get-Item $outPath).Length / 1KB)
Write-Output "wrote sprites.js  ($($sprites.Count) tiles, $kb KB)"
